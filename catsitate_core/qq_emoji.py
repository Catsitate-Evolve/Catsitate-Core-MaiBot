def load_emoji_table() -> dict[str, str]:
    """表情表(id 字符串 -> 描述),兼容 msg_react 的接口形状。"""

    return {str(emoji_id): desc for emoji_id, desc in AVAILABLE_REACT_EMOJIS.items()}


def grouped_emoji_table() -> str:
    """分组表情表(稳定段用):每组一行「【组名】id 名称, ...」。"""

    lines = []
    for label, hint, ids in REACT_EMOJI_GROUPS:
        items = ", ".join(f"{i} {AVAILABLE_REACT_EMOJIS[i]}" for i in ids if i in AVAILABLE_REACT_EMOJIS)
        lines.append(f"【{label}】({hint}) {items}")
    return chr(10).join(lines)
