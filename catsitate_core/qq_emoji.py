def load_emoji_table() -> dict[str, str]:
    """表情表(id 字符串 -> 描述),兼容 msg_react 的接口形状。"""

    return {str(emoji_id): desc for emoji_id, desc in AVAILABLE_REACT_EMOJIS.items()}


def grouped_emoji_table() -> str:
    """分组表情表(稳定段用):每组一行「【组名】id 名称, ...」。"""

    lines = []
    for label, hint, ids in REACT_EMOJI_GROUPS:
        items = ", ".join(f"{i} {AVAILABLE_REACT_EMOJIS[i]}" for i in ids if i in AVAILABLE_REACT_EMOJIS)
        lines.append(f"【{label}】({hint}) {items}")
    return chr(10).join(lines)


def compact_emoji_table() -> str:
    """扁平表情列表(id 升序):保留给旧调用方与测试。"""

    return ", ".join(f"{i} {d}" for i, d in sorted(AVAILABLE_REACT_EMOJIS.items()))


def resolve_emoji_by_name(text: str) -> tuple[int | None, str]:
    """按名称/别名解析表情 id:精确命中优先,其次唯一子串命中;歧义或未知返回原因。"""

    query = str(text or "").strip().strip("[]【】「」:： ").lower()
    if not query:
        return None, "表情名称为空"
    if query.isdigit():
        candidate = int(query)
        if candidate in AVAILABLE_REACT_EMOJIS:
            return candidate, ""
        return None, f"表情 id {candidate} 不在表内"
    exact = [i for name, i in EMOJI_NAMES.items() if name.lower() == query]
    exact += [i for name, i in REACT_EMOJI_ALIASES.items() if name.lower() == query]
    if exact:
        return exact[0], ""
    fuzzy: list[int] = []
    for name, i in list(EMOJI_NAMES.items()) + list(REACT_EMOJI_ALIASES.items()):
        low = name.lower()
        if (low in query or query in low) and i not in fuzzy:
            fuzzy.append(i)
    if len(fuzzy) == 1:
        return fuzzy[0], ""
    if not fuzzy:
        return None, f"没有与「{text}」匹配的表情;可用名称见分组表"
    names = "、".join(f"{i} {AVAILABLE_REACT_EMOJIS.get(i, '未知')}" for i in fuzzy[:6])
    return None, f"「{text}」匹配到多个表情({names}),请用更精确的名称或直接给 id"
